ns.LANGS = { "auto", "ptBR", "enUS" }

--- "auto" resolves to the game's own language.
function ns.Lang()
    local v = ns.db and ns.db.lang or "auto"
    if v == "ptBR" or v == "enUS" then return v end
    return GetLocale() == "ptBR" and "ptBR" or "enUS"
end

function ns.ApplyLanguage()
    for k in pairs(L) do L[k] = nil end
    for k, v in pairs(enUS) do L[k] = v end
    if ns.Lang() == "ptBR" then
        for k, v in pairs(ptBR) do L[k] = v end
    end
end

ns.ApplyLanguage()
